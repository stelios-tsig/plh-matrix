def bst(seq):
    root = None
    def ins(n, v):
        if n is None: return [v, None, None]
        if v < n[0]: n[1] = ins(n[1], v)
        else: n[2] = ins(n[2], v)
        return n
    import copy
    for v in seq: root = ins(root, v)
    return copy.deepcopy(root)
def bst_steps(seq):
    out = []
    for i in range(1, len(seq) + 1): out.append(bst(seq[:i]))
    return out
def path_to(seq, v):
    t, p = bst(seq), []
    while t:
        p.append(t[0])
        if v == t[0]: break
        t = t[1] if v < t[0] else t[2]
    return p

